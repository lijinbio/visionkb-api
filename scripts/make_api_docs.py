def main() -> int:
    if os.environ.get("VISIONKB_IT") != "1":
        print('needs the live services: eval "$(scripts/local_services.sh env)"', file=sys.stderr)
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        tokens = Path(tmp) / "tokens.tsv"
        tokens.write_text(f"{TOKEN}\tread,proposals:read,proposals:write\n")
        s = Settings(
            release_dir=Path(os.environ["VISIONKB_TEST_RELEASE_DIR"]),
            neo4j_uri=os.environ["NEO4J_URI"],
            neo4j_user=os.environ.get("NEO4J_USER", "neo4j"),
            neo4j_password_file=Path(os.environ["NEO4J_PASSWORD_FILE"]),
            pg_dsn_file=Path(os.environ["VISIONKB_PG_DSN_FILE"]),
            tokens_file=tokens,
        )
        hdr = {"Authorization": f"Bearer {TOKEN}"}
        out = [INTRO]
        with TestClient(create_app(s)) as c:
            rels = c.get("/v1/relationships?subject=HGNC:10012", headers=hdr).json()["data"]
            ids = {
                "rho_rp4": next(e["edge_id"] for e in rels if e["object"]["id"] == "MONDO:0013395"),
                "rho_rod": next(e["edge_id"] for e in rels if e["object"]["id"] == "CL:0000604"),
            }
            for title, sig, text, calls in SECTIONS:
                out.append(f"## {title}\n\n`{sig}`\n\n{text}\n")
                for method, path, body in calls:
                    path = path.format(**ids)
                    if method == "GET-NO-DATABASES":
                        # Same release, Neo4j and PostgreSQL not configured: the 503 readiness answer.
                        bare = Settings(release_dir=s.release_dir, tokens_file=tokens)
                        with TestClient(create_app(bare)) as c2:
                            r = c2.get(path)
                        req = f'curl -s "$VISIONKB_API_URL{path}"   # an instance without Neo4j/PostgreSQL'
                    elif method == "GET":
                        noauth = path in ("/v1/health", "/v1/ready")
                        r = c.get(path, headers={} if noauth else hdr)
                        auth = "" if noauth else ' -H "Authorization: Bearer $TOKEN"'
                        req = f'curl -s{auth} "$VISIONKB_API_URL{path}"'
                    else:
                        r = c.post(path, headers=hdr, json=body)
                        req = (
                            f'curl -s -X POST -H "Authorization: Bearer $TOKEN" -H "Content-Type: application/json" '
                            f'"$VISIONKB_API_URL{path}" -d @proposal.json\n# proposal.json:\n'
                            + json.dumps(body, indent=2)
                        )
                    out.append(
                        f"```bash\n{req}\n```\n\nHTTP {r.status_code}\n\n```json\n{json.dumps(r.json(), indent=2, ensure_ascii=False)}\n```\n"
                    )
    text = "\n".join(out)
    (ROOT / "docs" / "api.md").write_text(text.rstrip() + "\n", encoding="utf-8")
    print(f"docs/api.md: {len(text)} characters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
