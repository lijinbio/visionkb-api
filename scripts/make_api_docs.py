INTRO = """# VisionKB API reference (v0.1)

Base path `/v1`, JSON only. The machine-readable schema is [`openapi.json`](openapi.json)
(also served at `/v1/openapi.json`, with an interactive page at `/v1/docs`).

Every response, success or error, is one envelope:

```json
{"status": "ok" | "error", "kg_release": "visionkb-YYYY.MM.N", "data": ..., "page": {"limit", "offset", "total"} | null,
 "warnings": ["..."], "error": {"code", "message"} | null}
```

- `kg_release` names the release every value came from; atlas rows also carry `dataset_version`.
- Lists: default `limit` 50, capped at 200 (`VISIONKB_MAX_ROWS`; a larger request is capped and a warning
  says so). A response aims at 24,000 characters at most: if a list would exceed it, it is cut from the
  end, `page` keeps the requested limit and total, and a warning gives the number returned, so page on
  with `offset`.
- Errors never fall back to invented data: unknown ids give `404 not_found`, malformed CURIEs
  `400 invalid_curie`, predicates outside Biolink 4.4.6 `400 unknown_predicate`, Biolink predicates
  that the release does not use `400 predicate_not_in_release`, request-schema problems `422
  invalid_request`, a down database `503 neo4j_unavailable` / `postgres_unavailable`.
- Auth: `Authorization: Bearer <token>`. Tokens live in `VISIONKB_API_TOKENS_FILE`, one
  `token<TAB>scopes` per line: a TAB between token and scopes, scopes separated by commas and/or spaces
  (`token<TAB>read`, `token<TAB>read,proposals:read`); `#` starts a comment; tokens have 16+ characters.
  Scopes: `read` (all GET endpoints except health/ready), `proposals:read`, `proposals:write`.
  `/v1/health` and `/v1/ready` need no token.
- The API reads only the release bundle directory (`VISIONKB_RELEASE_DIR`), Neo4j and PostgreSQL.
  Paths in dataset records (`h5ad_path`, `soma_uri`, `bind.path`) are metadata for clients that run
  where the data are; the service never opens them.

The examples below are real responses from the synthetic fixture release
(`tests/fixtures/make_fixture.py`: real HGNC/CL/UBERON/MONDO/EFO identifiers, **synthetic values**),
generated by `scripts/make_api_docs.py`. `$TOKEN` stands for a token with the needed scope.
"""

